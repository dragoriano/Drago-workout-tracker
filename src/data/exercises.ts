export function getExerciseMetadata(name: string): ExerciseMetadata | undefined {
  return EXERCISE_DATABASE.find(e => e.name.toLowerCase() === name.toLowerCase());
}

export function getExerciseMuscleGroups(name: string): string[] {
  const ex = EXERCISE_DATABASE.find(e => e.name.toLowerCase() === name.toLowerCase());
  return ex ? ex.muscleGroups : [];
}

export const MUSCLE_REGION_MAPPING: Record<string, string[]> = EXERCISE_DATABASE.reduce((acc, ex) => {
  ex.muscleGroups.forEach(group => {
    if (!acc[group]) acc[group] = [];
    if (!acc[group].includes(ex.name)) acc[group].push(ex.name);
  });
  return acc;
}, {} as Record<string, string[]>);
